_pos = itertools.cycle([3, 1, 2, 0])

def P(ch, lv, stem, ok_text, wrong, why):
    """Soal dengan kunci di posisi bergilir. wrong = tiga pengecoh."""
    pos = next(_pos)
    opts = list(wrong)
    opts.insert(pos, ok_text)
    return Q(ch, lv, stem, *opts, "abcd"[pos], why)

