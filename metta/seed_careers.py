def _tags(field, skills, base, kw):
    out = list(base[field])
    for tag, words in kw.items():
        if tag not in out and any(s in words for s in skills): out.append(tag)
    return ",".join(out[:3])

def build_extra():
    """Hasil: (careers, careers_id, skills, skills_id, flags)
    careers   : tuple seperti CAREERS di seed.py, untuk karier baru saja
    careers_id: {nama Inggris: (nama, deskripsi, tugas, pendidikan, contoh project, jenjang)}
    skills    : {nama Inggris: kategori} untuk skill baru;  skills_id: {nama Inggris: nama Indonesia}
    flags     : {nama Inggris: (field Inggris, trend 0/1, baru 0/1)} untuk SEMUA 100 karier"""
    careers, careers_id, skills, skills_id, flags = [], {}, {}, {}, {}
    for idx, (idn, field, major, sk_csv, desc_id, fl) in enumerate(ROWS):
        terms = [t.strip() for t in sk_csv.split(",")]
        def en_skill(t): return EXISTING.get(t) or SK.get(t) or t
        if idx in ORIGINAL:
            flags[ORIGINAL[idx]] = (FIELD_EN[field], int("g" in fl), int("n" in fl)); continue
        for t in terms:
            n = en_skill(t)
            if t not in EXISTING:
                skills[n] = "soft" if t in SOFT else "technical"; skills_id[n] = t
        name_en, desc_en = EN[idn]
        sk = [(en_skill(t), 3 if i == 0 else 2) for i, t in enumerate(terms)]
        s_en = ", ".join(en_skill(t) for t in terms); s_id = ", ".join(terms)
        mj_en = {"TKJ": "SMK TKJ", "AK": "SMK AK"}.get(major, "SMK (any major)")
        edu_en = {"TKJ": "SMK TKJ, then certificates or D3/S1 Informatics.", "AK": "SMK AK, then certificates or D3/S1 Accounting.",
                  "TKJ & AK": "SMK TKJ or AK, then certificates or a related D3/S1.", "Semua jurusan": "SMK of any major, then training, an internship or a related D3/S1."}[major]
        edu_id = {"TKJ": "SMK TKJ, lalu sertifikat atau D3/S1 Informatika.", "AK": "SMK AK, lalu sertifikat atau D3/S1 Akuntansi.",
                  "TKJ & AK": "SMK TKJ atau AK, lalu sertifikat atau D3/S1 yang terkait.", "Semua jurusan": "SMK jurusan apa pun, lalu pelatihan, magang, atau D3/S1 yang terkait."}[major]
        careers.append((name_en, FIELD_EN[field], desc_en, "Daily work uses: " + s_en + ". " + desc_en, edu_en,
                        "Make a small practice project that shows " + en_skill(terms[0]) + (" and " + en_skill(terms[1]) if len(terms) > 1 else "") + ", and save it as evidence.",
                        "Start as a trainee or junior, grow into a full " + name_en + ", then become a senior or team lead.",
                        _tags(field, terms, F_INT, K_INT), _tags(field, terms, F_STR, K_STR), MAJORS[major], sk))
        careers_id[name_en] = (idn, desc_id, "Sehari-hari memakai: " + s_id + ". " + desc_id, edu_id,
                               "Buat project latihan kecil yang menunjukkan " + terms[0] + (" dan " + terms[1] if len(terms) > 1 else "") + ", lalu simpan sebagai bukti.",
                               "Mulai sebagai trainee atau junior, lalu menjadi " + idn + " penuh, kemudian senior atau ketua tim.")
        flags[name_en] = (FIELD_EN[field], int("g" in fl), int("n" in fl))
    return careers, careers_id, skills, skills_id, flags
